/**
 * Cross-origin isolation defaults for WASM apps (`docs/SPEC.md` section 1.20, issue `toolchain#81`).
 *
 * Free-threaded CPython 3.15t on WebAssembly uses pthreads, which require `SharedArrayBuffer`.
 * Browsers only expose `SharedArrayBuffer` when `self.crossOriginIsolated === true`:
 * `Cross-Origin-Opener-Policy: same-origin` together with `Cross-Origin-Embedder-Policy: require-corp`
 * (or `credentialless`), plus `Cross-Origin-Resource-Policy: same-origin` on our own assets.
 */

const val STAGE_WASM_ISOLATION_TASK = "stageWasmCrossOriginIsolation"
const val WASM_ISOLATION_DIRECTORY = "pythonWasmIsolation"
const val WASM_COEP_PROPERTY = "python.wasm.coep"
const val DEFAULT_WASM_COEP_POLICY = "require-corp"
val VALID_WASM_COEP_POLICIES = setOf("require-corp", "credentialless")

const val WASM_HEADERS_FILE = "_headers"
const val WASM_COI_SERVICE_WORKER_FILE = "coi-serviceworker.js"
const val WASM_COI_CHECK_PAGE_FILE = "coi-check.html"
const val WASM_WEBPACK_CONFIG_FILE = "python-cross-origin-isolation.js"

/**
 * Resolves the `Cross-Origin-Embedder-Policy` value for WASM builds.
 * Defaults to [DEFAULT_WASM_COEP_POLICY] (`require-corp`); `credentialless` is the other valid option.
 */
fun resolveWasmCoepPolicy(raw: String?): String {
    val policy = raw?.trim().orEmpty().ifEmpty { DEFAULT_WASM_COEP_POLICY }
    require(policy in VALID_WASM_COEP_POLICIES) {
        "Invalid -P$WASM_COEP_PROPERTY='$policy': Cross-Origin-Embedder-Policy for WASM must be " +
            "'require-corp' or 'credentialless'."
    }
    return policy
}

/**
 * The three HTTP response headers that make a WASM page cross-origin isolated and mark its own
 * assets safe to embed under `require-corp`.
 */
fun wasmCrossOriginHeaders(coepPolicy: String = DEFAULT_WASM_COEP_POLICY): Map<String, String> {
    val resolved = resolveWasmCoepPolicy(coepPolicy)
    return linkedMapOf(
        "Cross-Origin-Opener-Policy" to "same-origin",
        "Cross-Origin-Embedder-Policy" to resolved,
        "Cross-Origin-Resource-Policy" to "same-origin",
    )
}

/**
 * Renders the Cloudflare Pages and Netlify `_headers` file emitted next to the WASM distribution.
 */
fun renderWasmHeadersFile(coepPolicy: String = DEFAULT_WASM_COEP_POLICY): String {
    val headers = wasmCrossOriginHeaders(coepPolicy)
    return buildString {
        appendLine("# Generated by org.thisisthepy.python.multiplatform (toolchain#81).")
        appendLine("# Cross-origin isolation headers required by CPython 3.15t pthreads (SharedArrayBuffer).")
        appendLine("/*")
        for ((name, value) in headers) {
            appendLine("  $name: $value")
        }
    }
}

/**
 * Renders our own service-worker fallback (`coi-serviceworker.js`) for static hosts that cannot set
 * HTTP response headers (such as GitHub Pages).
 *
 * The header comment states the two costs required by `toolchain#81`:
 * 1. One reload on the first visit (the service worker must install, claim the page, and reload).
 * 2. No effect when service workers are unavailable (insecure contexts other than localhost, private
 *    modes or webviews that disable service workers).
 */
fun renderWasmCoiServiceWorkerScript(coepPolicy: String = DEFAULT_WASM_COEP_POLICY): String {
    val resolved = resolveWasmCoepPolicy(coepPolicy)
    return """
        |// Generated by org.thisisthepy.python.multiplatform (toolchain#81).
        |// Service-worker fallback that re-serves responses with Cross-Origin-Opener-Policy and
        |// Cross-Origin-Embedder-Policy headers on hosts that cannot set HTTP headers (e.g. GitHub Pages).
        |//
        |// Cost and limits:
        |// 1. Costs one reload on the first visit: the first page load registers this worker and reloads
        |//    once the worker controls the page so the document response carries COOP/COEP.
        |// 2. Has no effect when service workers are unavailable (non-HTTPS origins other than localhost,
        |//    or browsers/webviews with service workers disabled).
        |(function () {
        |  "use strict";
        |  var COOP = "same-origin";
        |  var COEP = "$resolved";
        |  var CORP = "same-origin";
        |
        |  if (typeof window === "undefined") {
        |    self.addEventListener("install", function () {
        |      self.skipWaiting();
        |    });
        |    self.addEventListener("activate", function (event) {
        |      event.waitUntil(self.clients.claim());
        |    });
        |    self.addEventListener("fetch", function (event) {
        |      var request = event.request;
        |      if (request.cache === "only-if-cached" && request.mode !== "same-origin") {
        |        return;
        |      }
        |      event.respondWith(
        |        fetch(request).then(function (response) {
        |          if (!response || response.status === 0) {
        |            return response;
        |          }
        |          var headers = new Headers(response.headers);
        |          headers.set("Cross-Origin-Opener-Policy", COOP);
        |          headers.set("Cross-Origin-Embedder-Policy", COEP);
        |          headers.set("Cross-Origin-Resource-Policy", CORP);
        |          return new Response(response.body, {
        |            status: response.status,
        |            statusText: response.statusText,
        |            headers: headers
        |          });
        |        })
        |      );
        |    });
        |    return;
        |  }
        |
        |  if (self.crossOriginIsolated) {
        |    return;
        |  }
        |  if (!window.isSecureContext || !("serviceWorker" in navigator)) {
        |    console.error(
        |      "python-multiplatform WASM: self.crossOriginIsolated is false and service workers are unavailable. " +
        |        "Serve the app with Cross-Origin-Opener-Policy: " + COOP +
        |        " and Cross-Origin-Embedder-Policy: " + COEP + "."
        |    );
        |    return;
        |  }
        |  var currentScript = document.currentScript;
        |  var workerUrl = currentScript && currentScript.src ? currentScript.src : "$WASM_COI_SERVICE_WORKER_FILE";
        |  navigator.serviceWorker.register(workerUrl).then(
        |    function (registration) {
        |      if (registration.active && !navigator.serviceWorker.controller) {
        |        window.location.reload();
        |        return;
        |      }
        |      navigator.serviceWorker.addEventListener("controllerchange", function () {
        |        window.location.reload();
        |      });
        |    },
        |    function (err) {
        |      console.error("python-multiplatform WASM: failed to register " + workerUrl + ":", err);
        |    }
        |  );
        |})();
        |
    """.trimMargin()
}

/**
 * Renders `coi-check.html`, a diagnostic page emitted alongside the WASM distribution that loads
 * [WASM_COI_SERVICE_WORKER_FILE] and verifies `self.crossOriginIsolated` and `SharedArrayBuffer`,
 * failing loudly if the page is not isolated so the failure happens at startup rather than later
 * inside a thread (`toolchain#81` item 5).
 */
fun renderWasmCoiCheckPage(): String =
    """
        |<!DOCTYPE html>
        |<html lang="en">
        |<head>
        |  <meta charset="utf-8">
        |  <title>WASM Cross-Origin Isolation Check</title>
        |  <script src="$WASM_COI_SERVICE_WORKER_FILE"></script>
        |</head>
        |<body>
        |  <pre id="coi-status">Checking cross-origin isolation...</pre>
        |  <script>
        |    (function () {
        |      var status = document.getElementById("coi-status");
        |      var isolated = self.crossOriginIsolated === true;
        |      var hasSab = typeof SharedArrayBuffer === "function";
        |      if (isolated && hasSab) {
        |        status.textContent = "OK: self.crossOriginIsolated is true and SharedArrayBuffer is available.";
        |      } else {
        |        var msg = "ERROR: self.crossOriginIsolated is " + self.crossOriginIsolated +
        |          " (SharedArrayBuffer: " + typeof SharedArrayBuffer + "). " +
        |          "A page that is not cross-origin isolated cannot start the threaded CPython 3.15t runtime. " +
        |          "Configure Cross-Origin-Opener-Policy: same-origin and Cross-Origin-Embedder-Policy: require-corp " +
        |          "(or credentialless), or load " + "$WASM_COI_SERVICE_WORKER_FILE" + " before the app bundle.";
        |        status.textContent = msg;
        |        console.error(msg);
        |      }
        |    })();
        |  </script>
        |</body>
        |</html>
        |
    """.trimMargin()

/**
 * Renders the webpack `config.d` script that configures `devServer.headers` for Kotlin/Wasm `run`
 * and `dev` tasks (`wasmJsBrowserDevelopmentRun`, `wasmJsBrowserProductionRun`, etc.).
 */
fun renderWasmWebpackConfigScript(coepPolicy: String = DEFAULT_WASM_COEP_POLICY): String {
    val resolved = resolveWasmCoepPolicy(coepPolicy)
    return """
        |// Generated by org.thisisthepy.python.multiplatform (toolchain#81).
        |// Enables cross-origin isolation on the Kotlin/Wasm webpack dev server so CPython 3.15t pthreads
        |// have SharedArrayBuffer.
        |config.devServer = config.devServer || {};
        |config.devServer.headers = Object.assign(
        |  {
        |    "Cross-Origin-Opener-Policy": "same-origin",
        |    "Cross-Origin-Embedder-Policy": "$resolved",
        |    "Cross-Origin-Resource-Policy": "same-origin"
        |  },
        |  config.devServer.headers || {}
        |);
        |
    """.trimMargin()
}

/**
 * Writes `webpack.config.d/python-cross-origin-isolation.js` inside [wasmPackageDir]
 * (`<rootBuildDir>/wasm/packages/<module>`), where Kotlin/Wasm's `KotlinWebpack` task reads
 * generated `webpack.config.d` `.js` snippets.
 */
fun patchWasmWebpackConfigDirectory(wasmPackageDir: File, coepPolicy: String = DEFAULT_WASM_COEP_POLICY): File {
    val configDir = File(wasmPackageDir, "webpack.config.d").apply { mkdirs() }
    val scriptFile = File(configDir, WASM_WEBPACK_CONFIG_FILE)
    scriptFile.writeText(renderWasmWebpackConfigScript(coepPolicy))
    return scriptFile
}

/**
 * Writes `_headers`, `coi-serviceworker.js` and `coi-check.html` into [destinationDir], replacing
 * any previous contents.
 */
fun writeWasmCrossOriginIsolationAssets(destinationDir: File, coepPolicy: String = DEFAULT_WASM_COEP_POLICY) {
    val resolved = resolveWasmCoepPolicy(coepPolicy)
    destinationDir.deleteWithoutFollowingLinks()
    destinationDir.mkdirs()
    File(destinationDir, WASM_HEADERS_FILE).writeText(renderWasmHeadersFile(resolved))
    File(destinationDir, WASM_COI_SERVICE_WORKER_FILE).writeText(renderWasmCoiServiceWorkerScript(resolved))
    File(destinationDir, WASM_COI_CHECK_PAGE_FILE).writeText(renderWasmCoiCheckPage())
}

/**
 * Emits the static cross-origin isolation assets (`_headers`, `coi-serviceworker.js`, `coi-check.html`)
 * into `build/pythonWasmIsolation/`, wired into `wasmJsProcessResources` so they ship at the root of
 * the WASM browser distribution.
 */
abstract class StageWasmCrossOriginIsolationTask : DefaultTask() {
    @get:Input
    abstract val coepPolicy: Property<String>

    @get:OutputDirectory
    abstract val destinationDir: DirectoryProperty

    @TaskAction
    fun stage() {
        val dir = destinationDir.get().asFile
        val policy = resolveWasmCoepPolicy(coepPolicy.orNull)
        writeWasmCrossOriginIsolationAssets(dir, policy)
        logger.lifecycle(
            "Staged WASM cross-origin isolation assets ($WASM_HEADERS_FILE, $WASM_COI_SERVICE_WORKER_FILE, " +
                "$WASM_COI_CHECK_PAGE_FILE; COEP=$policy) into $dir",
        )
    }
}

/**
 * Registers [STAGE_WASM_ISOLATION_TASK] and wires it into `wasmJsProcessResources` and every
 * `wasmJs*Webpack` task when the consumer's build declares a `wasmJs` target.
 */
fun configureWasmCrossOriginIsolation(project: Project) {
    val coepProvider = project.providers.gradleProperty(WASM_COEP_PROPERTY).orElse(DEFAULT_WASM_COEP_POLICY)
    val destination = project.layout.buildDirectory.dir(WASM_ISOLATION_DIRECTORY)
    val stageTask = project.tasks.register(STAGE_WASM_ISOLATION_TASK, StageWasmCrossOriginIsolationTask::class.java) {
        group = PythonPlugin.TASK_GROUP
        description = "Generates WASM cross-origin isolation headers (_headers) and service-worker fallback (coi-serviceworker.js)"
        coepPolicy.set(coepProvider)
        destinationDir.set(destination)
    }

    project.tasks.matching { it.name == "wasmJsProcessResources" }.configureEach {
        dependsOn(stageTask)
        (this as? Copy)?.from(stageTask)
    }

    val modulePrefix = if (project == project.rootProject) {
        project.name
    } else {
        "${project.rootProject.name}-${project.path.removePrefix(":").replace(":", "-")}"
    }
    project.tasks.matching { it.name.startsWith("wasmJs") && it.name.endsWith("Webpack") }.configureEach {
        dependsOn(stageTask)
        val wasmPackageDir = project.rootProject.layout.buildDirectory.dir("wasm/packages/$modulePrefix")
        doFirst("configureWasmCrossOriginIsolationHeaders") {
            patchWasmWebpackConfigDirectory(wasmPackageDir.get().asFile, coepProvider.get())
        }
    }
}
