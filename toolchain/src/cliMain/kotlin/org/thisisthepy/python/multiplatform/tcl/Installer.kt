package org.thisisthepy.python.multiplatform.tcl

import kotlinx.coroutines.runBlocking
import org.thisisthepy.python.multiplatform.packpack.dependency.backend.BackendInterface
import org.thisisthepy.python.multiplatform.packpack.dependency.backend.BackendType
import java.io.File

private const val PYPROJECT_FILE = "pyproject.toml"

private const val GIT_ENTRY = ".git"

/**
 * Finds the project `tcl install` adds to, starting at [startDir], without ever reaching an
 * unrelated ancestor project:
 *
 * - [startDir]'s own `pyproject.toml` always counts.
 * - Inside a git repository (a directory holding a `.git` directory, or a `.git` file for a
 *   worktree), the search walks up to the nearest `pyproject.toml`, and stops at the repository
 *   root, which is the last directory checked. A `pyproject.toml` above the repository belongs to
 *   another project.
 * - Outside any repository there is no boundary to trust, so only [startDir] counts: a stray
 *   `pyproject.toml` in a parent or the home directory is never edited.
 *
 * Returns null when no project qualifies; [Installer.install] then initializes one in [startDir].
 */
fun findProjectRoot(startDir: File): File? {
    val start = startDir.canonicalFile
    if (File(start, PYPROJECT_FILE).isFile) return start

    val repositoryRoot = generateSequence(start) { it.parentFile }.firstOrNull { File(it, GIT_ENTRY).exists() }
        ?: return null
    var current: File? = start.parentFile
    while (current != null && current.path.length >= repositoryRoot.path.length) {
        if (File(current, PYPROJECT_FILE).isFile) return current
        if (current == repositoryRoot) break
        current = current.parentFile
    }
    return null
}

/**
 * `tcl install <package>` -- the one command from GitHub issue thisisthepy/toolchain#1
 * ("toolchain-lite") this module makes real end to end.
 *
 * `pypackpack` already has every piece this needs (`docs/SPEC.md` "Project creation", "Dev
 * environment dependency management"): `pypackpack init` and `pypackpack add <name>`. What a
 * python-only user coming from `pip install`/`npm install` is missing is the two-step dance of
 * running `init` first if nothing exists yet, then `add`. [install] collapses both into the one
 * call the issue's usage example shows.
 *
 * Deliberately calls `dependency.backend.BackendInterface` directly -- the same layer
 * `:toolchain`'s `InstallDependenciesTask.installWithPackpack` uses -- rather than the
 * `dependency.frontend`/`middleware` layers `pypackpack`'s own CLI is built on. Those resolve the
 * project root from the JVM-global `user.dir` system property (`pypackpack`'s internal
 * `findProjectRoot()`); the backend layer takes `workingDir: File?` as an explicit parameter
 * instead, which is what lets [install] and its tests pass a temp directory directly instead of
 * mutating global JVM state.
 */
class Installer(
    private val backend: BackendInterface = BackendInterface.create(BackendType.UV),
) {
    /**
     * Adds [packageName] as a dependency of the project rooted at (or above) [workingDir],
     * initializing a fresh `pyproject.toml` there first via `uv init --bare --no-workspace` if [findProjectRoot]
     * finds none. Returns the same `Result<String>` `pypackpack`'s backend does: `uv`'s own
     * combined stdout/stderr on success, or the failure it hit -- including a failed `initProject`,
     * which short-circuits before `addDependencies` is ever attempted.
     */
    suspend fun install(
        packageName: String,
        workingDir: File,
    ): Result<String> {
        backend.initialize()

        val existingRoot = findProjectRoot(workingDir)
        if (existingRoot == null) {
            // `--bare` matches what `pypackpack init` itself does (pypackpack's `docs/SPEC.md`
            // "Project creation"): only `pyproject.toml` is generated by `uv`, nothing else assumed.
            // `--no-workspace` keeps `uv` from registering the new project as a member of an
            // ancestor's workspace, which would write `[tool.uv.workspace]` into that ancestor.
            val initResult =
                backend.initProject(
                    path = null,
                    extraArgs = mapOf("bare" to "", "no-workspace" to ""),
                    workingDir = workingDir,
                )
            if (initResult.isFailure) return initResult
        }

        return backend.addDependencies(
            packageName = null,
            dependencies = listOf(packageName),
            extraArgs = null,
            workingDir = existingRoot ?: workingDir,
        )
    }
}

/** Synchronous entry point for callers (the CLI, tests) that are not already inside a coroutine. */
fun installBlocking(
    packageName: String,
    workingDir: File,
    installer: Installer = Installer(),
): Result<String> = runBlocking { installer.install(packageName, workingDir) }
